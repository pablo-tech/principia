#!/usr/bin/env python3
"""Project `.retrieval/exclude` into the entry point's prose, so the rule is written once.

    gen_exclude.py --repo <path>                     rewrite the block in the entry point
    gen_exclude.py --repo <path> --check             say whether it is stale, exit 1
    gen_exclude.py --repo <path> --ref origin/main   read the commit, not the checkout
    gen_exclude.py --repo <path> --print             print the block and write nothing
    gen_exclude.py --repo <path> --entry OTHER.md    a document other than the declared entry

**The file is canonical and the prose is its projection, not the other way round.** A
repository that forbids opening a class of file states that rule to a reader, in prose,
because a reader is who it was written for; an unattended service in front of the same
files needs the same rule as data. Where both exist one of them is a copy, and the copy
that can be regenerated is the one to keep — so the list of bullets a reader sees is
written from the file a process asks, and `--check` is what makes the two provably the
same text rather than the same intention.

**The block carries the rules and no count of what they match.** Every other generated
surface here states its own size, because its subject *is* the corpus it indexes; this
one's subject is a ten-line file. A count of matched paths would make the entry point
stale the first time anybody committed a record under an already-excluded subtree —
staleness over a change that has nothing to do with the rule, reported against the one
document every session reads. `exclude.py --check` is where that count belongs, and it
is printed on every verify run.
"""
import pathlib
import re
import sys

import config
import exclude
import scan

BEGIN = "<!-- BEGIN EXCLUDE — generated by gen_exclude.py, do not edit by hand -->"
END = "<!-- END EXCLUDE -->"


def block_for(rules):
    """The bullet list as it should be: the glob a process reads, then the reason."""
    out = [BEGIN, ""]
    for glob, reason in rules:
        out.append(f"- `{glob}` — {reason}")
    out += ["", END]
    return "\n".join(out)


def render(tree, entry, rules):
    """The entry point with its block rewritten. Raises on a document with no markers."""
    text = tree.read_optional(entry)
    if text is None:
        raise SystemExit(f"{entry}: not in {tree.describe()}, so there is no prose to project into")
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), text, flags=re.S)
    if not m:
        raise SystemExit(
            f"{entry}: no {BEGIN} … {END} markers. Put them around the list the exclude "
            "file is the canonical form of, leaving the prose that introduces it outside."
        )
    return text[: m.start()] + block_for(rules) + text[m.end():]


def main(argv):
    opts, rest, i = {}, [], 0
    flags = ("--repo", "--ref", "--entry")
    while i < len(argv):
        a = argv[i]
        if a in ("--check", "--print"):
            opts[a.lstrip("-")] = True
        elif a in flags and i + 1 < len(argv):
            opts[a.lstrip("-")] = argv[i + 1]
            i += 1
        else:
            rest.append(a)
        i += 1
    if rest or "repo" not in opts:
        print(__doc__.split("\n\n")[1].rstrip(), file=sys.stderr)
        return 2

    tree = scan.Tree(opts["repo"], ref=opts.get("ref"))
    entry = opts.get("entry") or config.read(opts["repo"])["entry"]
    raw = tree.read_optional(exclude.PATH)
    if raw is None:
        print(f"{exclude.PATH}: not in {tree.describe()}, so there is nothing to project — "
              f"write the rules there, or remove the markers from {entry}", file=sys.stderr)
        return 1
    rules = exclude.parse(raw, where=f"{tree.describe()}:{exclude.PATH}")
    new = render(tree, entry, rules)
    counted = f"{len(rules)} exclude rules"

    if opts.get("print"):
        sys.stdout.write(block_for(rules) + "\n")
        return 0

    p = pathlib.Path(tree.repo) / entry
    old = p.read_text() if p.exists() else None
    if new == old:
        print(f"{entry}: exclude block up to date, {counted}")
        return 0
    if opts.get("check"):
        print(f"{entry}: exclude block STALE, {counted}", file=sys.stderr)
        return 1
    p.write_text(new)
    print(f"{entry}: exclude block rewritten, {counted}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
