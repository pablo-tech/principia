#!/usr/bin/env python3
"""Generate or refresh the `## Contents` index at the top of a long document.

Idempotent: it rewrites whatever sits between the BEGIN/END markers, and on a first
run it inserts the block above the rule that introduces the first `##` heading. Re-run
it any time headings change.

    gen_toc.py --repo <path> <file>...          index the named documents
    gen_toc.py --repo <path> --all              index every document the predicate selects
    gen_toc.py --repo <path> --all --check      name the stale ones, write nothing, exit 1
    gen_toc.py --repo <path> --list             print the predicate's count and nothing else

**Which documents carry a block is a predicate, not a list.** At least MIN_BYTES bytes,
at least MIN_HEADINGS `##`/`###` headings, and no `## Contents` written by hand. The
third clause is a safety property rather than a convenience: a question-keyed Contents,
or a table whose first column is the section, is a better artefact than a heading list,
and generating over either destroys information. A hand-written Contents outside the
markers is refused loudly.

`--check` is why a generator may be trusted in a repository with no continuous
integration at all: a generator nothing runs is a staleness source wearing a marker that
promises otherwise, and `--check` makes staleness a one-command fact that the
repository's own verify script runs.
"""
import pathlib
import re
import sys

import scan
from slugify import Slugger

BEGIN = "<!-- BEGIN CONTENTS — generated by gen_toc.py, do not edit by hand -->"
END = "<!-- END CONTENTS -->"

MIN_BYTES = 20_000
MIN_HEADINGS = 8

HAND_WRITTEN = re.compile(r"^## Contents\s*$", re.M)


def block_for(items):
    slug = Slugger()
    out = [BEGIN, "## Contents", ""]
    for level, text in items:
        text = scan.anchor_text(text)
        label = scan.label(text)
        s = slug(text)
        if level == 2:
            out.append(f"- **[{label}](#{s})**")
        else:
            # 4 spaces: python-markdown's sane_lists needs a full indent step to nest
            out.append(f"    - [{label}](#{s})")
    out += ["", END, ""]
    return "\n".join(out)


def insertion_offset(t):
    """Offset of the start of the line the block is inserted above.

    The first `##` heading is the anchor, except that a bare `---` immediately above it
    is the rule that introduces it — and a block dropped between the rule and the
    heading it rules off reads as part of the section. So the block goes above the rule
    where there is one. This is load-bearing in both directions: a document with no
    `---` at all must still be indexable, and a document whose rule sits immediately
    above its first heading must not be rewritten on a run that changes nothing.
    """
    m = re.search(r"^## ", t, flags=re.M)
    if not m:
        return None
    head = t[: m.start()].rstrip("\n")
    nl = head.rfind("\n")
    if head[nl + 1:].strip() == "---":
        return nl + 1
    return m.start()


def render(p, rel):
    """The document as it should be. Raises SystemExit on a document it must not touch."""
    t = scan.strip_block(p.read_text())
    if HAND_WRITTEN.search(t):
        raise SystemExit(
            f"{rel}: a '## Contents' heading sits outside the generated markers. "
            "Refusing to write a second one — remove the markers or the heading."
        )
    pos = insertion_offset(t)
    if pos is None:
        raise SystemExit(f"{rel}: no '## ' heading to index")
    items = scan.headings(t)
    return t[:pos] + block_for(items) + "\n" + t[pos:], len(items)


def candidates(tree, scope=("*.md",), verbose=True):
    """Every tracked document the predicate selects, with the predicate's own inputs."""
    picked = []
    for name in tree.paths(scope=scope):
        raw = tree.read(name)
        if raw is None:
            continue
        t = scan.strip_block(raw)
        size, n, hand = len(raw.encode()), len(scan.headings(t)), bool(HAND_WRITTEN.search(t))
        if size < MIN_BYTES or n < MIN_HEADINGS:
            continue
        if hand:
            if verbose:
                print(f"{name}: {size} B, {n} headings — SKIP, hand-written Contents")
            continue
        if verbose:
            print(f"{name}: {size} B, {n} headings — selected")
        picked.append(name)
    return picked


def main(argv):
    opts, names, i = {}, [], 0
    while i < len(argv):
        a = argv[i]
        if a in ("--all", "--check", "--list"):
            opts[a.lstrip("-")] = True
        elif a in ("--repo", "--scope") and i + 1 < len(argv):
            opts[a.lstrip("-")] = argv[i + 1]
            i += 1
        elif a.startswith("-"):
            opts["bad"] = True
        else:
            names.append(a)
        i += 1
    walk = opts.get("all", False)
    if opts.get("list") and "repo" in opts and not names:
        # The count alone, for a verify script that reports the predicate's set beside
        # the set that actually carries a block: the two converge once every selected
        # document has been indexed, and the gap is the figure somebody wants.
        tree = scan.Tree(opts["repo"])
        scope = tuple(opts["scope"].split(",")) if "scope" in opts else ("*.md",)
        print(len(candidates(tree, scope=scope, verbose=False)))
        return 0
    if opts.get("bad") or "repo" not in opts or (walk and names) or not (walk or names):
        print(__doc__.split("\n\n")[2].rstrip(), file=sys.stderr)
        return 2

    tree = scan.Tree(opts["repo"])
    scope = tuple(opts["scope"].split(",")) if "scope" in opts else ("*.md",)
    rels = candidates(tree, scope=scope) if walk else names
    if walk:
        print(f"-- {len(rels)} documents selected by the predicate "
              f"({MIN_BYTES} B, {MIN_HEADINGS} headings, no hand-written Contents)")

    stale = []
    for rel in rels:
        p = pathlib.Path(rel)
        if not p.is_absolute():
            p = tree.repo / rel
        new, n = render(p, rel)
        if new == p.read_text():
            print(f"{rel}: up to date, {n} headings")
            continue
        stale.append(rel)
        if opts.get("check"):
            print(f"{rel}: STALE, {n} headings")
        else:
            p.write_text(new)
            print(f"{rel}: indexed {n} headings")

    if opts.get("check") and stale:
        print(f"-- {len(stale)} stale: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
